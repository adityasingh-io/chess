// Generate src/types/export.ts from the pipeline's JSON Schema (web/schema/export.schema.json).
// `node scripts/gen-types.mjs --check` exits 1 when the committed file is out of date.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";

const web = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(web, "src/types/export.ts");

export async function generate() {
  const schema = JSON.parse(readFileSync(join(web, "schema/export.schema.json"), "utf8"));
  // Pydantic titles every field; without this each one becomes its own alias (Ts, Games1, ...).
  const untitle = (node, keep) => {
    if (Array.isArray(node)) return node.forEach((n) => untitle(n, false));
    if (!node || typeof node !== "object") return;
    if (!keep) delete node.title;
    for (const [k, v] of Object.entries(node)) untitle(v, k === "$defs" ? "defs" : keep === "defs");
  };
  untitle(schema, true);
  schema.title = "Export";
  const body = await compile(schema, "Export", {
    bannerComment: "/* Generated by scripts/gen-types.mjs from schema/export.schema.json. Do not edit. */",
    unreachableDefinitions: true,
    additionalProperties: false,
    format: false,
  });
  return body;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const text = await generate();
  if (process.argv.includes("--check")) {
    const same = readFileSync(out, "utf8") === text;
    console.log(same ? "types: up to date" : "types: out of date, run npm run types");
    process.exit(same ? 0 : 1);
  }
  writeFileSync(out, text);
  console.log("types: wrote src/types/export.ts");
}
