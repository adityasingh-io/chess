import { copyFileSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { defineConfig, type Plugin } from "vitest/config";
import react from "@vitejs/plugin-react";

// The service worker (sw/sw.template.js) gets the build's file list and an id, so each build installs fresh.
function serviceWorker(): Plugin {
  return {
    name: "coach-service-worker",
    apply: "build",
    generateBundle(_options, bundle) {
      // Maia-2's WebAssembly runtime (14 MB) is fetched when a Maia bot is first used, not at install.
      const files = Object.keys(bundle).filter((f) => !f.endsWith(".map") && !/ort-wasm.*\.wasm$/.test(f))
        .concat(["favicon.svg", "manifest.webmanifest", "icon-192.png", "icon-512.png", "apple-touch-icon.png"]);
      const build = Date.now().toString(36);
      const source = readFileSync(new URL("./sw/sw.template.js", import.meta.url), "utf8")
        .replace("self.__BUILD__", JSON.stringify(build)).replace("self.__FILES__", JSON.stringify(files));
      this.emitFile({ type: "asset", fileName: "sw.js", source });
    },
  };
}

// Cross-origin isolation lets the multi-threaded Stockfish build run; without it the app falls back to
// the single-threaded build. The deployed site gets the same headers from the generated _headers file.
const isolation = {
  "Cross-Origin-Opener-Policy": "same-origin",
  "Cross-Origin-Embedder-Policy": "require-corp",
};

// A personal site, so search engines are asked to stay away unless the build sets COACH_NOINDEX=0: a
// robots meta tag, robots.txt, and an X-Robots-Tag header in _headers (Cloudflare Pages reads that file).
const noindex = process.env.COACH_NOINDEX !== "0";
function hosting(): Plugin {
  return {
    name: "coach-hosting",
    apply: "build",
    transformIndexHtml: () => noindex ? [{ tag: "meta", attrs: { name: "robots", content: "noindex, nofollow" }, injectTo: "head" }] : [],
    generateBundle() {
      this.emitFile({ type: "asset", fileName: "robots.txt", source: `User-agent: *\n${noindex ? "Disallow" : "Allow"}: /\n` });
      const headers = { ...isolation, ...(noindex ? { "X-Robots-Tag": "noindex, nofollow" } : {}) };
      const lines = Object.entries(headers).map(([k, v]) => `  ${k}: ${v}`).join("\n");
      this.emitFile({ type: "asset", fileName: "_headers", source: `# Generated by vite.config.ts.\n/*\n${lines}\n` });
    },
  };
}

// GitHub Pages serves the site under the repo's name (adityasingh.io/chess/) and answers any path that isn't
// a file with 404.html, so that build gets the sub-path and a copy of index.html as 404.html. It can't send
// headers, so the service worker adds the cross-origin isolation ones (sw/sw.template.js).
const pagesBase = process.env.COACH_GITHUB_PAGES_BASE;
function githubPages(): Plugin {
  return {
    name: "coach-github-pages",
    apply: "build",
    writeBundle(options) {
      if (pagesBase) copyFileSync(join(options.dir!, "index.html"), join(options.dir!, "404.html"));
    },
  };
}

export default defineConfig({
  base: pagesBase ?? "/",
  plugins: [react(), serviceWorker(), hosting(), githubPages()],
  // One .env for the pipeline and the app, at the repo root. Vite exposes only VITE_ variables (the
  // Supabase URL and publishable key) to the bundle; the pipeline's secrets never reach it.
  envDir: "..",
  server: { headers: isolation },
  // onnxruntime-web (Maia-2) finds its .wasm next to its own module, which pre-bundling would move.
  optimizeDeps: { exclude: ["onnxruntime-web"] },
  worker: { format: "es" },
  preview: { headers: isolation },
  test: {
    environment: "jsdom",
    globals: true,
    include: ["tests/**/*.test.{ts,tsx}"],
    setupFiles: ["tests/setup.ts"],
    // Tests run with sync off, as in CI, whatever the repo-root .env holds.
    env: { VITE_SUPABASE_URL: "", VITE_SUPABASE_PUBLISHABLE_KEY: "" },
  },
});
